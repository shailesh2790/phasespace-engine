"""A small reservoir simulator, purely to generate truth that CRM must recover.

The build plan asks for connectivity fixtures generated by OPM Flow. OPM is the
right long-term answer and this is not a substitute for it. It exists because
the alternative -- generating test data from the CRM equations themselves and
then checking that CRM recovers it -- tests only that an optimiser can invert
arithmetic, which is exactly the self-consistency this project refuses
everywhere else.

So this solves different physics. Single-phase slightly-compressible flow on a
two-dimensional grid:

    phi * c_t * V * dp/dt = sum_faces T * (p_neighbour - p) + q_well

with injectors at specified rate, producers on a specified bottomhole pressure
through a Peaceman well index, and backward Euler in time. Nothing in it is a
tank, a time constant, or a connectivity coefficient. Those are emergent
properties that CRM claims to be able to read back out of the rates, and the
point of this module is to have an independent answer to compare against.

Truth connectivity comes from a steady-state tracer solve on the converged
velocity field: release unit tracer at one injector, advect it, and see which
producers it arrives at. That is a transport calculation, not a curve fit.

Units are field throughout: psi, days, bbl, ft, md, cp.
"""
from __future__ import annotations

from dataclasses import dataclass, field as dataclass_field

import numpy as np
from scipy.sparse import csr_matrix, diags
from scipy.sparse.linalg import spsolve

# Darcy's law in field units: bbl/day = 1.127e-3 * k[md] * A[ft2] * dp[psi]
# / (mu[cp] * L[ft]).
DARCY_FIELD = 1.127e-3


@dataclass
class Grid:
    nx: int
    ny: int
    dx_ft: float = 200.0
    dy_ft: float = 200.0
    thickness_ft: float = 30.0
    porosity: float = 0.22
    permeability_md: np.ndarray = None
    viscosity_cp: float = 1.0
    total_compressibility_psi: float = 1.2e-5

    def __post_init__(self):
        if self.nx < 3 or self.ny < 3:
            raise ValueError("grid must be at least 3x3, got %dx%d" % (self.nx, self.ny))
        if self.permeability_md is None:
            self.permeability_md = np.full((self.ny, self.nx), 100.0)
        self.permeability_md = np.asarray(self.permeability_md, dtype=float)
        if self.permeability_md.shape != (self.ny, self.nx):
            raise ValueError("permeability must be shaped (ny, nx) = (%d, %d), got %s"
                             % (self.ny, self.nx, self.permeability_md.shape))
        if np.any(self.permeability_md <= 0.0):
            raise ValueError("permeability must be positive everywhere")

    @property
    def n_cells(self) -> int:
        return self.nx * self.ny

    @property
    def cell_volume_bbl(self) -> float:
        """Bulk volume in barrels: 1 bbl = 5.615 ft3."""
        return self.dx_ft * self.dy_ft * self.thickness_ft / 5.615

    def index(self, ix: int, iy: int) -> int:
        return iy * self.nx + ix


@dataclass
class Well:
    name: str
    ix: int
    iy: int
    radius_ft: float = 0.354
    skin: float = 0.0


@dataclass
class SyntheticCase:
    """What the simulator produced, and the truth it was produced from."""

    times_days: np.ndarray
    injection: np.ndarray
    production: np.ndarray
    bottomhole_psia: np.ndarray
    true_connectivity: np.ndarray
    injector_names: list
    producer_names: list
    injector_xy: np.ndarray
    producer_xy: np.ndarray
    average_pressure_psia: np.ndarray = None
    notes: list = dataclass_field(default_factory=list)


def _transmissibilities(grid: Grid) -> tuple:
    """Harmonic-average face transmissibilities, in bbl/day/psi."""
    k = grid.permeability_md
    mu = grid.viscosity_cp

    area_x = grid.dy_ft * grid.thickness_ft
    area_y = grid.dx_ft * grid.thickness_ft

    # Harmonic mean is the correct average for series flow through two cells;
    # an arithmetic mean lets a single high-permeability cell short-circuit its
    # low-permeability neighbour, which is how a synthetic case acquires
    # connectivity the geology does not have.
    kx = 2.0 * k[:, :-1] * k[:, 1:] / (k[:, :-1] + k[:, 1:])
    ky = 2.0 * k[:-1, :] * k[1:, :] / (k[:-1, :] + k[1:, :])

    tx = DARCY_FIELD * kx * area_x / (mu * grid.dx_ft)
    ty = DARCY_FIELD * ky * area_y / (mu * grid.dy_ft)
    return tx, ty


def _well_index(grid: Grid, well: Well) -> float:
    """Peaceman's productivity index for a vertical well in a grid block."""
    k = grid.permeability_md[well.iy, well.ix]
    # Equivalent radius for an isotropic square block.
    r_e = 0.28 * np.sqrt(grid.dx_ft ** 2 + grid.dy_ft ** 2) / 2.0
    return (2.0 * np.pi * DARCY_FIELD * k * grid.thickness_ft
            / (grid.viscosity_cp * (np.log(r_e / well.radius_ft) + well.skin)))


def _pressure_matrix(grid: Grid) -> csr_matrix:
    """The flow operator: off-diagonals are face transmissibilities."""
    tx, ty = _transmissibilities(grid)
    n = grid.n_cells
    rows, cols, values = [], [], []
    diagonal = np.zeros(n)

    for iy in range(grid.ny):
        for ix in range(grid.nx - 1):
            a, b = grid.index(ix, iy), grid.index(ix + 1, iy)
            t = tx[iy, ix]
            rows += [a, b]
            cols += [b, a]
            values += [t, t]
            diagonal[a] -= t
            diagonal[b] -= t

    for iy in range(grid.ny - 1):
        for ix in range(grid.nx):
            a, b = grid.index(ix, iy), grid.index(ix, iy + 1)
            t = ty[iy, ix]
            rows += [a, b]
            cols += [b, a]
            values += [t, t]
            diagonal[a] -= t
            diagonal[b] -= t

    matrix = csr_matrix((values, (rows, cols)), shape=(n, n))
    return matrix + diags(diagonal)


def simulate(
    grid: Grid,
    injectors: list,
    producers: list,
    injection_schedule: np.ndarray,
    producer_bhp_psia: np.ndarray,
    days: float = 3600.0,
    steps: int = 120,
    initial_pressure_psia: float = 3000.0,
) -> SyntheticCase:
    """Run the model and return rates plus the true connectivity.

    ``injection_schedule`` is (steps, n_injectors) in bbl/day. Producers are
    held at ``producer_bhp_psia``, either a scalar or (steps, n_producers), and
    their rates fall out of the pressure solution -- which is the whole point.
    A synthetic case with producers on fixed *rates* would tell CRM nothing,
    since CRM exists to explain how rates respond.
    """
    n_inj, n_prod = len(injectors), len(producers)
    if n_inj == 0 or n_prod == 0:
        raise ValueError("need at least one injector and one producer")

    injection_schedule = np.atleast_2d(np.asarray(injection_schedule, dtype=float))
    if injection_schedule.shape != (steps, n_inj):
        raise ValueError("injection schedule must be (%d, %d), got %s"
                         % (steps, n_inj, injection_schedule.shape))
    if np.isscalar(producer_bhp_psia):
        producer_bhp_psia = np.full((steps, n_prod), float(producer_bhp_psia))
    producer_bhp_psia = np.asarray(producer_bhp_psia, dtype=float)

    dt = days / steps
    n = grid.n_cells
    flow = _pressure_matrix(grid)

    accumulation = (grid.porosity * grid.total_compressibility_psi
                    * grid.cell_volume_bbl / dt)
    storage = diags(np.full(n, accumulation))

    producer_wi = np.array([_well_index(grid, w) for w in producers])
    producer_cells = np.array([grid.index(w.ix, w.iy) for w in producers])
    injector_cells = np.array([grid.index(w.ix, w.iy) for w in injectors])

    pressure = np.full(n, float(initial_pressure_psia))
    rates = np.zeros((steps, n_prod))
    pressures_at_wells = np.zeros((steps, n_prod))
    average_pressure = np.zeros(steps)

    # Producers enter the matrix as a pressure-dependent sink: q = WI*(p - pwf),
    # so WI sits on the diagonal and WI*pwf on the right-hand side. Treating
    # them explicitly instead would make the timestep conditionally stable for
    # no benefit.
    well_diagonal = np.zeros(n)
    for cell, wi in zip(producer_cells, producer_wi):
        well_diagonal[cell] += wi
    operator = (storage - flow + diags(well_diagonal)).tocsc()

    for step in range(steps):
        rhs = accumulation * pressure
        rhs[injector_cells] += injection_schedule[step]
        rhs[producer_cells] += producer_wi * producer_bhp_psia[step]

        pressure = spsolve(operator, rhs)
        rates[step] = producer_wi * (pressure[producer_cells]
                                     - producer_bhp_psia[step])
        pressures_at_wells[step] = producer_bhp_psia[step]
        average_pressure[step] = float(pressure.mean())

    connectivity = tracer_allocation(grid, injectors, producers, pressure,
                                     producer_cells, rates[-1],
                                     injection_schedule[-1])

    times = np.arange(1, steps + 1) * dt
    return SyntheticCase(
        times_days=times,
        injection=injection_schedule,
        production=rates,
        bottomhole_psia=pressures_at_wells,
        true_connectivity=connectivity,
        injector_names=[w.name for w in injectors],
        producer_names=[w.name for w in producers],
        injector_xy=np.array([[w.ix * grid.dx_ft, w.iy * grid.dy_ft]
                              for w in injectors]),
        producer_xy=np.array([[w.ix * grid.dx_ft, w.iy * grid.dy_ft]
                              for w in producers]),
        average_pressure_psia=average_pressure,
        notes=["Connectivity is a steady-state tracer allocation on the final "
               "velocity field, not a curve fit."],
    )


def tracer_allocation(grid: Grid, injectors: list, producers: list,
                      pressure: np.ndarray, producer_cells: np.ndarray,
                      producer_rates: np.ndarray,
                      injection_rates: np.ndarray) -> np.ndarray:
    """True connectivity: where each injector's water actually arrives.

    Releases unit tracer at one injector and solves a steady upwind advection
    on the converged pressure field, then reads the fraction arriving at each
    producer. This shares no mathematics with CRM -- no exponential, no time
    constant, no least squares -- which is the entire reason it can serve as
    truth for a CRM test.

    The producer sink is the producer's *rate*, in bbl/day. Using its
    productivity index instead is a factor of a few hundred, and the symptom is
    not an obviously wrong answer: the tracer simply never drains, fills the
    domain uniformly, and every injector reports a perfectly even split across
    producers. Degenerate answers that look like clean fractions -- exactly
    0.333, exactly 0.5 -- are the signature.
    """
    tx, ty = _transmissibilities(grid)
    n = grid.n_cells
    producer_rates = np.asarray(producer_rates, dtype=float)
    injection_rates = np.asarray(injection_rates, dtype=float)

    faces = []
    for iy in range(grid.ny):
        for ix in range(grid.nx - 1):
            a, b = grid.index(ix, iy), grid.index(ix + 1, iy)
            faces.append((a, b, tx[iy, ix] * (pressure[a] - pressure[b])))
    for iy in range(grid.ny - 1):
        for ix in range(grid.nx):
            a, b = grid.index(ix, iy), grid.index(ix, iy + 1)
            faces.append((a, b, ty[iy, ix] * (pressure[a] - pressure[b])))

    outflow = np.zeros(n)
    for cell, rate in zip(producer_cells, producer_rates):
        outflow[cell] += max(float(rate), 0.0)

    # The flux topology does not depend on which injector is releasing tracer,
    # so it is assembled once rather than per injector.
    total_out = np.zeros(n)
    inflow_terms = {}
    for a, b, flux in faces:
        if flux >= 0.0:
            total_out[a] += flux
            inflow_terms.setdefault(b, []).append((a, flux))
        else:
            total_out[b] += -flux
            inflow_terms.setdefault(a, []).append((b, -flux))

    connectivity = np.zeros((len(injectors), len(producers)))

    for i, injector in enumerate(injectors):
        source_cell = grid.index(injector.ix, injector.iy)
        rows, cols, values = [], [], []
        rhs = np.zeros(n)

        for cell in range(n):
            if cell == source_cell:
                rows.append(cell)
                cols.append(cell)
                values.append(1.0)
                rhs[cell] = 1.0
                continue
            rows.append(cell)
            cols.append(cell)
            values.append(max(total_out[cell] + outflow[cell], 1e-12))
            for upstream, flux in inflow_terms.get(cell, []):
                rows.append(cell)
                cols.append(upstream)
                values.append(-flux)

        matrix = csr_matrix((values, (rows, cols)), shape=(n, n))
        concentration = spsolve(matrix.tocsc(), rhs)
        concentration = np.clip(np.nan_to_num(concentration), 0.0, 1.0)

        # Tracer mass reaching each producer per unit time, as a fraction of
        # what this injector put in. Row sums below one mean water left the
        # pattern, which in a closed grid should not happen and is therefore a
        # check on the solve rather than a finding.
        captured = producer_rates * concentration[producer_cells]
        rate_in = float(injection_rates[i])
        if rate_in > 0.0:
            connectivity[i] = captured / rate_in

    return connectivity


def five_spot(spacing_cells: int = 8, **grid_kwargs) -> tuple:
    """The canonical pattern: one injector, four producers at the corners."""
    nx = ny = 2 * spacing_cells + 1
    grid = Grid(nx=nx, ny=ny, **grid_kwargs)
    injectors = [Well("I-1", spacing_cells, spacing_cells)]
    producers = [
        Well("P-1", 1, 1),
        Well("P-2", nx - 2, 1),
        Well("P-3", 1, ny - 2),
        Well("P-4", nx - 2, ny - 2),
    ]
    return grid, injectors, producers


def step_response_connectivity(
    grid: Grid,
    injectors: list,
    producers: list,
    base_rates: np.ndarray,
    producer_bhp_psia: float,
    bump_bbl_day: float = 300.0,
    days: float = 6000.0,
    steps: int = 200,
) -> np.ndarray:
    """True CRM connectivity: dq_j / di_i at steady state.

    This is the quantity CRM actually fits, and it is *not* the same as where
    the injected water ends up. The difference is large enough to change what a
    report means, so both are computed here and the tests compare each against
    the right one.

    On the asymmetric two-injector case in the tests:

        tracer allocation   [[0.68, 0.32, 0.00], [0.05, 0.38, 0.57]]
        step response       [[0.41, 0.36, 0.23], [0.23, 0.36, 0.41]]

    Water from I-1 overwhelmingly reaches P-1 and never reaches P-3. But
    *turning I-1 up* raises pressure across the whole connected volume, and a
    quarter of that increase comes out of P-3 -- which is a long way from where
    I-1's water goes.

    The two coincide only when the reservoir is genuinely compartmentalised, so
    that pressure and water travel the same restricted paths. In a
    well-connected sand they diverge badly, and reading a fitted f_ij as
    "the share of this injector's water arriving at that producer" is then
    wrong in a way that no amount of fit quality will reveal.

    Computed by finite difference on the simulator: run the base case, bump one
    injector, difference the converged producer rates. Expensive -- one full
    simulation per injector plus one -- and only used to generate fixtures.
    """
    base_rates = np.asarray(base_rates, dtype=float)
    if base_rates.size != len(injectors):
        raise ValueError("need one base rate per injector")
    if bump_bbl_day <= 0.0:
        raise ValueError("bump must be positive, got %r" % (bump_bbl_day,))

    def converged_rates(rates: np.ndarray) -> np.ndarray:
        schedule = np.tile(rates, (steps, 1))
        case = simulate(grid, injectors, producers, schedule, producer_bhp_psia,
                        days=days, steps=steps)
        return case.production[-1]

    base = converged_rates(base_rates)
    response = np.zeros((len(injectors), len(producers)))
    for i in range(len(injectors)):
        bumped = base_rates.copy()
        bumped[i] += bump_bbl_day
        response[i] = (converged_rates(bumped) - base) / bump_bbl_day
    return response
