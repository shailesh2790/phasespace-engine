"""Download the real 3W instances we need, and nothing else.

Only classes 0 (normal), 8 (hydrate in production line) and 9 (hydrate in
service line), and only *real* instances -- simulated ones are generated by
someone else's model, so scoring our physics against them would be comparing
two models rather than testing one against a measurement.

Petrobras 3W 2.0.0, CC BY 4.0, https://github.com/petrobras/3W
"""
import json
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

CACHE = Path(sys.argv[1] if len(sys.argv) > 1 else "data/3w")
API = "https://api.github.com/repos/petrobras/3W/contents/dataset/%d?per_page=100"
RAW = "https://raw.githubusercontent.com/petrobras/3W/main/dataset/%d/%s"

# Every real instance of all three classes. The normal class was capped at a
# sample first, which was a mistake twice over: a zero-false-alarm claim is
# exactly the claim that gets stronger with more negatives, and the capped run
# was also silently truncated by a dropped connection, so the sample was 55
# rather than the 120 intended. Take all of them and retry properly.
WANTED = {8: None, 9: None, 0: None}

# Simulated instances, used for *training only*. Petrobras ships them for
# exactly this: the real events are too few to train on and must stay
# untouched as a test set. Scoring physics against them would be comparing
# two models, so they never appear in a validation number.
SIMULATED = {8: None}

RETRIES = 4


def listing(cls):
    with urllib.request.urlopen(API % cls, timeout=120) as response:
        return json.load(response)


def retrieve(url, target):
    """Download with retries.

    GitHub drops long sequences of raw requests, and an unhandled
    RemoteDisconnected halfway through leaves a partial corpus that still
    analyses cleanly -- which is how a published result came to rest on 55
    instances instead of the intended 120 without anything looking wrong.
    """
    for attempt in range(1, RETRIES + 1):
        try:
            urllib.request.urlretrieve(url, target)
            return
        except Exception as error:                       # noqa: BLE001
            if attempt == RETRIES:
                raise
            print("   retry %d/%d after %s" % (attempt, RETRIES, type(error).__name__),
                  flush=True)
            time.sleep(2.0 * attempt)


def main():
    for cls, limit in list(WANTED.items()) + [("sim-%d" % c, l) for c, l in SIMULATED.items()]:
        simulated = isinstance(cls, str)
        if simulated:
            cls = int(cls.split("-")[1])
        folder = CACHE / ("sim%d" % cls if simulated else str(cls))
        folder.mkdir(parents=True, exist_ok=True)
        if simulated:
            entries = [e for e in listing(cls)
                       if e["name"].startswith("SIMULATED")]
        else:
            entries = [e for e in listing(cls)
                       if not e["name"].startswith(("SIMULATED", "DRAWN"))]
        entries.sort(key=lambda e: e["name"])
        if limit:
            # Evenly spaced through the sorted list so the sample spans wells
            # rather than taking the first N, which would be one well's year.
            step = max(len(entries) // limit, 1)
            entries = entries[::step][:limit]

        print("class %d: %d %s instances" % (cls, len(entries),
              "simulated" if simulated else "real"), flush=True)
        for index, entry in enumerate(entries, 1):
            target = folder / entry["name"]
            if target.exists() and target.stat().st_size == entry["size"]:
                continue
            retrieve(RAW % (cls, entry["name"]), target)
            if index % 20 == 0:
                print("   %d/%d" % (index, len(entries)), flush=True)
        have = len(list(folder.glob("*.parquet")))
        print("   %d/%d on disk, %.1f MB"
              % (have, len(entries),
                 sum(f.stat().st_size for f in folder.glob("*.parquet")) / 1e6),
              flush=True)
        if have < len(entries):
            raise SystemExit(
                "%s is incomplete (%d of %d) -- rerun rather than "
                "analysing a partial corpus" % (folder.name, have, len(entries)))


if __name__ == "__main__":
    main()
